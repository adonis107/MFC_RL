from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Dict, Optional, Sequence

from .core.artifacts import _metadata, _write_csv, _write_json, apply_overrides, load_json_config
from .core.registry import (
    BASELINE_ALGORITHMS,
    CONTINUOUS_ALGORITHMS,
    DEFAULT_DEVICE,
    ENVIRONMENTS,
    EXACT_ALGORITHMS,
    FINITE_ALGORITHMS,
    PATHWISE_ALGORITHMS,
)
from .runner import (
    run_sweep,
    run_train,
)
from .diagnostics.functional_law import run_functional_law_diagnostic
from .diagnostics.gradient import run_gradient_diagnostic
from .diagnostics.perturbation import run_perturbation_diagnostic
from .diagnostics.sensitivity import run_sensitivity_diagnostic


def merged_cli_config(args: argparse.Namespace) -> Dict[str, Any]:
    config = load_json_config(getattr(args, "config", None))
    if getattr(args, "env", None) is not None:
        config["env"] = args.env
    if getattr(args, "algorithm", None) is not None:
        config["algorithm"] = args.algorithm
    train = config.setdefault("train", {})
    env_config = config.setdefault("env_config", {})
    if getattr(args, "output_dir", None) is not None:
        train["output_dir"] = args.output_dir
    if getattr(args, "run_name", None) is not None:
        train["run_name"] = args.run_name
    if getattr(args, "seed", None) is not None:
        train["seed"] = args.seed
    if getattr(args, "steps", None) is not None:
        train["steps"] = args.steps
    if getattr(args, "lr", None) is not None:
        train["lr"] = args.lr
    if getattr(args, "device", None) is not None:
        env_config["device"] = args.device
    if getattr(args, "dtype", None) is not None:
        env_config["dtype"] = args.dtype
    return apply_overrides(config, getattr(args, "overrides", []) or [])


def _add_common_arguments(parser: argparse.ArgumentParser, *, algorithm: bool = True) -> None:
    parser.add_argument("--config", help="Path to a JSON experiment config.")
    parser.add_argument("--env", choices=sorted(ENVIRONMENTS), help="Environment registry name.")
    if algorithm:
        parser.add_argument(
            "--algorithm",
            choices=sorted(FINITE_ALGORITHMS | EXACT_ALGORITHMS | PATHWISE_ALGORITHMS | CONTINUOUS_ALGORITHMS | BASELINE_ALGORITHMS),
            help="Algorithm registry name.",
        )
    parser.add_argument("--output-dir", help="Directory where run artifacts are written.")
    parser.add_argument("--run-name", help="Run directory name. A timestamped name is generated by default.")
    parser.add_argument("--seed", type=int, help="Random seed.")
    parser.add_argument("--steps", type=int, help="Training steps.")
    parser.add_argument("--lr", type=float, help="Learning rate.")
    parser.add_argument("--device", help=f"Torch device, e.g. cuda or cpu. Defaults to {DEFAULT_DEVICE}.")
    parser.add_argument("--dtype", help="Torch dtype, e.g. float64.")
    parser.add_argument(
        "--set",
        dest="overrides",
        action="append",
        default=[],
        help="Override a JSON field with dotted.path=json_value. May be repeated.",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="MFC experiment runner.")
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in (
        "train",
        "diagnose-perturbation",
        "diagnose-gradient",
        "diagnose-sensitivity",
        "diagnose-functional-law",
        "score-validation",
        "application-diagnostics",
        "study",
        "sweep",
    ):
        child = subparsers.add_parser(command)
        _add_common_arguments(child)
    catalog = subparsers.add_parser("catalog")
    catalog.add_argument("--output-dir", default="runs", help="Directory where catalog artifacts are written.")
    catalog.add_argument("--run-name", default="result_catalog", help="Catalog run directory name.")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "catalog":
        from .plot_specs import RESULT_CATALOG, catalog_rows

        run_dir = Path(args.output_dir) / args.run_name
        run_dir.mkdir(parents=True, exist_ok=True)
        _write_json(run_dir / "catalog.json", RESULT_CATALOG)
        _write_csv(run_dir / "catalog.csv", catalog_rows())
        _write_json(run_dir / "metadata.json", _metadata("catalog", {"output_dir": args.output_dir, "run_name": args.run_name}))
        _write_json(run_dir / "metrics.json", {"results": len(RESULT_CATALOG)})
        print(run_dir)
        return 0

    config = merged_cli_config(args)
    command = args.command
    if command == "train":
        result = run_train(config)
    elif command == "diagnose-perturbation":
        result = run_perturbation_diagnostic(config)
    elif command == "diagnose-gradient":
        result = run_gradient_diagnostic(config)
    elif command == "diagnose-sensitivity":
        result = run_sensitivity_diagnostic(config)
    elif command == "diagnose-functional-law":
        result = run_functional_law_diagnostic(config)
    elif command == "score-validation":
        from .studies import run_score_validation

        result = run_score_validation(config)
    elif command == "application-diagnostics":
        from .application import run_application_diagnostics

        result = run_application_diagnostics(config)
    elif command == "study":
        from .studies import run_study

        result = run_study(config)
    elif command == "sweep":
        result = run_sweep(config)
    else:
        raise ValueError(f"Unknown command {command!r}.")
    print(result.run_dir)
    return 0


_merged_cli_config = merged_cli_config


__all__ = ["build_parser", "main", "merged_cli_config", "_merged_cli_config"]
