def figure_checklist(env_name: str) -> pd.DataFrame:
    rows = []
    for key, spec in RESULT_CATALOG.items():
        rows.append(
            {
                "figure_family": key,
                "command_or_study": spec.get("command", spec.get("study", ",".join(spec.get("studies", [])))),
                "files": ", ".join(spec.get("files", [])),
                "notebook_section": _section_for_family(key, env_name),
            }
        )
    rows.extend(_environment_specific_rows(env_name))
    return pd.DataFrame(rows)



