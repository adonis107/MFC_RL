def global_figure_gap_table() -> pd.DataFrame:
    rows = []
    for env_name in DISCRETE_BENCHMARKS + CONTINUOUS_BENCHMARKS:
        table = figure_coverage_matrix(env_name)
        missing = table[table["status"].isin(["future", "study-needed"])]
        for _, row in missing.iterrows():
            rows.append({"env": env_name, **row.to_dict()})
    return pd.DataFrame(
        rows,
        columns=["env", "figure_or_result", "status", "notebook_helper", "artifact"],
    )



def _section_for_family(key: str, env_name: str) -> str:
    if key == "application":
        return f"{env_name} application diagnostics"
    if key in {"perturbation_geometry", "functional_law", "score_validation", "gradient_validation", "sensitivity_validation"}:
        return "universal diagnostics"
    if key in {
        "horizon_scaling",
        "budget_allocation",
        "particle_approximation",
        "particle_transfer",
        "ablation",
        "robustness",
        "signature_ablation",
        "adaptive_lambda",
        "optimizer_bias",
        "scaling",
    }:
        return "study sweeps"
    return "summary tables"



def _application_helper_name(env_name: str) -> str:
    if env_name in DISCRETE_BENCHMARKS:
        return "plot_discrete_main_results, plot_discrete_application_details"
    if env_name == "lq":
        return "plot_lq_main_results, plot_continuous_application_details"
    if env_name == "portfolio":
        return "plot_portfolio_main_results, plot_continuous_application_details"
    return "plot_pathwise_main_results, plot_continuous_application_details"



